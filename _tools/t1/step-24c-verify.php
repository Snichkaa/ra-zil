<?php
/**
 * Этап 2.4, шаг 3 — повторное чтение отдельным процессом.
 */
require dirname(__DIR__, 2) . '/wp-load.php';
global $wpdb;

$NEW = 'Возьмём на себя документы, транспорт, организацию захоронения и поминальный обед. Наш специалист приедет в любое время суток и будет рядом на всех этапах прощания.';
$OLD = 'Возьмём на себя документы, транспорт, кладбище и поминальный обед. Ритуальный агент приедет в любое время суток и будет рядом на всех этапах прощания.';

wp_cache_flush();
echo "wp_cache_flush() вызван\n\n";

echo "=== 2.4: повторное чтение post_excerpt ID=11 ===\n";
$raw = $wpdb->get_var( "SELECT post_excerpt FROM {$wpdb->posts} WHERE ID=11" );
echo "из wp_posts напрямую:\n[" . $raw . "]\n";
printf( "  %d байт / %d симв., md5=%s\n", strlen( $raw ), mb_strlen( $raw ), md5( $raw ) );
printf( "  сверка с подготовленным «стало»: %s\n", $raw === $NEW ? 'СОВПАЛО' : 'РАСХОЖДЕНИЕ' );
printf( "  равен ли прежнему «было»: %s (ожидается «нет»)\n", $raw === $OLD ? 'ДА — запись не прошла' : 'нет' );

echo "\nчерез get_post() (объектный кэш сброшен):\n";
$p = get_post( 11 );
echo '[' . $p->post_excerpt . "]\n";
printf( "  совпадает с прочитанным из wp_posts: %s\n", $p->post_excerpt === $raw ? 'да' : 'НЕТ' );

echo "\nчерез get_the_excerpt() — то, что увидит и карточка архива, и лид под H1:\n";
echo '[' . wp_strip_all_tags( get_the_excerpt( 11 ) ) . "]\n";

echo "\n=== контроль подстрок в post_excerpt ID=11 ===\n";
foreach ( array( 'кладбище и поминальный обед', 'Ритуальный агент', 'организацию захоронения', 'Наш специалист' ) as $s ) {
	printf( "  «%-30s» = %d\n", $s, mb_substr_count( $raw, $s ) );
}

echo "\nИТОГ ЭТАПА 2.4: " . ( $raw === $NEW ? 'СОВПАЛО' : 'РАСХОЖДЕНИЕ' ) . "\n";
exit( $raw === $NEW ? 0 : 14 );
