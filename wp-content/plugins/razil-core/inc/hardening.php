<?php
/**
 * Закрытие того, чем сайт не пользуется.
 *
 * Отдельный файл, а не строчка в functions.php темы и не догрузка
 * к inc/robots.php. Причины: тема сменяема, а запреты должны жить дольше
 * темы; robots.php — про индексацию, и складывать в него меры безопасности
 * значит через полгода искать их не там. Этот файл будет расти, и по имени
 * понятно, что в нём.
 *
 * Всё сделано фильтрами, а не правкой .htaccess: файл веб-сервера на хостинге
 * не под управлением репозитория, его перепишет панель или потеряет следующая
 * заливка. Фильтр переживает и обновление ядра, и перезаливку файлов,
 * и переезд на другой сервер.
 *
 * @package RazilCore
 */

// Прямой доступ к файлу запрещён.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/*
 * ============================================================================
 * XML-RPC
 * ============================================================================
 *
 * Точка входа удалённого управления: публикация из внешних программ,
 * мобильное приложение WordPress, Jetpack, пингбэки. Ничем из этого сайт
 * не пользуется — активен один плагин, публикация идёт через админку.
 *
 * Опасность не в утечке, а в двух вещах.
 *
 * Первая: метод system.multicall позволяет проверить сотни пар логин-пароль
 * в ОДНОМ запросе. Защита, считающая неудачные входы, такого перебора
 * не замечает — запрос-то один.
 *
 * Вторая описана ниже, у пингбэков.
 */

add_filter( 'xmlrpc_enabled', '__return_false' );

/**
 * Снятие пингбэк-методов со списка XML-RPC.
 *
 * Нужно отдельно от xmlrpc_enabled: тот фильтр закрывает только методы,
 * требующие авторизации. pingback.ping авторизации не требует и продолжает
 * отвечать даже при xmlrpc_enabled = false.
 *
 * Чем он опасен: pingback.ping заставляет наш сервер обратиться по любому
 * указанному адресу. Это превращает сайт в чужое орудие — им долбят третью
 * площадку, а в чёрные списки попадает наш адрес. Заодно это способ
 * прощупать закрытую сеть за сервером: обращение-то идёт изнутри.
 *
 * @param array<string, callable> $methods Методы XML-RPC.
 *
 * @return array<string, callable>
 */
function razil_drop_pingback_methods( array $methods ): array {
	unset(
		$methods['pingback.ping'],
		$methods['pingback.extensions.getPingbacks']
	);

	return $methods;
}
add_filter( 'xmlrpc_methods', 'razil_drop_pingback_methods' );

/*
 * ============================================================================
 * ПИНГБЭКИ
 * ============================================================================
 */

/*
 * Ни одна запись не принимает пингбэки, что бы ни стояло в её собственном
 * поле ping_status.
 *
 * Это код, поэтому мера переезжает вместе с плагином на любой сервер.
 * Настройка default_ping_status в базе, которую я тоже перевёл в closed,
 * работает иначе: она задаёт значение по умолчанию для НОВЫХ записей
 * и определяет, что показывает галочка в Настройки → Обсуждение. У уже
 * созданных записей своё поле, и настройка их не трогает.
 *
 * То есть нужны обе меры, и они не дублируют друг друга:
 *   фильтр   — гарантия поведения, переезжает с кодом;
 *   настройка— честность интерфейса и значение по умолчанию, живёт в базе
 *              и на новый сервер попадёт только вместе с дампом.
 */
add_filter( 'pings_open', '__return_false', 20 );

/**
 * Снятие заголовка X-Pingback.
 *
 * WordPress объявляет им адрес точки входа в каждом ответе. Раз методы
 * сняты, объявлять нечего, а лишняя подсказка сканеру ни к чему.
 *
 * @param array<string, string> $headers Заголовки ответа.
 *
 * @return array<string, string>
 */
function razil_drop_pingback_header( array $headers ): array {
	unset( $headers['X-Pingback'] );

	return $headers;
}
add_filter( 'wp_headers', 'razil_drop_pingback_header' );

/*
 * ============================================================================
 * КОММЕНТАРИИ
 * ============================================================================
 *
 * Сайт комментариев не показывает: ни один шаблон темы не выводит ни форму,
 * ни список. Но точка приёма wp-comments-post.php живёт своей жизнью, и боты
 * стучат прямо в неё, минуя разметку. Спам копился бы в базе незаметно —
 * увидеть его можно было бы только в разделе «Комментарии» админки, куда
 * никто не заходит.
 *
 * Устроено так же, как у пингбэков, и по тем же причинам:
 *   фильтр    — гарантия поведения, переезжает с кодом на любой сервер;
 *   настройка — значение по умолчанию для новых записей и честность
 *               галочки в Настройки → Обсуждение; живёт в базе и попадёт
 *               на новый сервер только вместе с дампом.
 *
 * Фильтр закрывает и приём: wp_handle_comment_submission спрашивает
 * comments_open перед тем, как что-либо записать, и отвечает отказом.
 *
 * Приоритет 20, как и у pings_open: позже значения по умолчанию, чтобы
 * при появлении плагина, открывающего комментарии, последнее слово
 * оставалось за этим файлом.
 */
add_filter( 'comments_open', '__return_false', 20 );
